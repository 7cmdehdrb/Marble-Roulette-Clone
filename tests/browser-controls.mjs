import assert from 'node:assert/strict';
import { mkdir, writeFile, readFile } from 'node:fs/promises';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright-core');
const baseURL = process.env.SMOKE_BASE_URL || 'http://localhost:4173';
await mkdir('research/browser-controls', { recursive: true });
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_EXECUTABLE || '/usr/bin/google-chrome', headless: true, args: ['--no-sandbox', '--disable-dev-shm-usage', '--disable-background-timer-throttling'] });
const checks = [];
try {
  const page = await browser.newPage({ viewport: { width: 390, height: 844 }, locale: 'ko-KR', acceptDownloads: true });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(baseURL);
  await page.locator('#loading').waitFor({ state: 'detached', timeout: 15000 });
  await page.locator('#closeNotice').click();
  await page.screenshot({ path: 'research/browser-controls/mobile-ready.png' });
  await page.locator('#btnToggleSettings').click();
  await page.locator('#chkDarkMode').uncheck({ timeout: 3000 });
  assert.equal(await page.locator('html').getAttribute('class'), 'light');
  await page.locator('[data-winner=multi]').click();
  assert.ok(await page.locator('#in_rangeStart').isVisible());
  await page.screenshot({ path: 'research/browser-controls/mobile-settings.png' });
  for (const width of [320, 390, 750, 751, 1024, 1440]) {
    await page.setViewportSize({ width, height: 900 });
    const dimensions = await page.locator('#settings').boundingBox();
    assert.ok(dimensions.x >= 0 && dimensions.x + dimensions.width <= width + 1, `settings overflow at ${width}`);
  }
  checks.push('responsive layouts at 320/390/750/751/1024/1440 pixels');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.locator('#btnMoreMaps').click();
  assert.equal(await page.locator('#mapList article').count(), 4);
  await page.screenshot({ path: 'research/browser-controls/mobile-maps.png' });
  await page.getByRole('button', { name: '욕망의 항아리 선택', exact: true }).click();
  assert.equal(await page.locator('#sltMap').inputValue(), '2');
  checks.push('mobile theme, winner range and map gallery');
  await page.locator('#in_names').fill('');
  await page.locator('#in_names').blur();
  assert.ok(await page.locator('#btnStart').isDisabled());
  await page.locator('#in_names').fill('가나/3*2,가나/3,다라\n__proto__');
  await page.locator('#in_names').blur();
  assert.equal(await page.evaluate(() => window.roulette.getCount()), 5);
  checks.push('empty input disables start; duplicate and special names work');
  await page.reload();
  await page.locator('#loading').waitFor({ state: 'detached' });
  assert.equal(await page.locator('#sltMap').inputValue(), '2');
  assert.equal(await page.locator('html').getAttribute('class'), 'light');
  assert.equal(await page.evaluate(() => window.roulette.getCount()), 5);
  checks.push('name, map and theme persistence after reload');
  await page.setViewportSize({ width: 1280, height: 900 });
  await page.locator('#chkAutoRecording').check();
  await page.evaluate(() => { document.querySelector('#btnStart').click(); document.querySelector('#btnReset').click(); });
  await page.waitForTimeout(500);
  const before = await page.evaluate(() => ({ active: window.roulette._isRunning, positions: window.roulette._marbles.map(m => [m.x, m.y]) }));
  await page.waitForTimeout(500);
  const after = await page.evaluate(() => ({ active: window.roulette._isRunning, positions: window.roulette._marbles.map(m => [m.x, m.y]) }));
  assert.equal(after.active, false);
  assert.deepEqual(before, after);
  checks.push('immediate recording cancellation leaves the new round stationary');
  await page.locator('#in_names').fill('수박,키위,귤');
  await page.locator('#in_names').blur();
  await page.locator('[data-winner=first]').click();
  await page.evaluate(() => window.roulette.setSpeed(15));
  const downloadPromise = page.waitForEvent('download', { timeout: 40000 });
  await page.locator('#btnStart').click();
  const download = await downloadPromise;
  const file = await download.path();
  const bytes = await readFile(file);
  assert.ok(bytes.length > 1000);
  assert.match(download.suggestedFilename(), /\.(webm|mp4)$/);
  if (download.suggestedFilename().endsWith('.webm')) assert.equal(bytes.subarray(0, 4).toString('hex'), '1a45dfa3');
  checks.push(`real recording download: ${download.suggestedFilename().split('.').pop()}, ${bytes.length} bytes`);
  await page.waitForFunction(() => document.querySelector('#settings').dataset.state === 'finished');
  await page.waitForFunction(() => !document.querySelector('#settings').classList.contains('hide'));
  await page.locator('#chkAutoRecording').uncheck();
  await page.locator('#btnStart').click();
  await page.waitForFunction(() => document.querySelector('#settings').dataset.state === 'running');
  await page.locator('#btnReset').click();
  assert.equal(await page.evaluate(() => window.roulette.getCount()), 3);
  checks.push('finished round restarts and resets correctly');
  assert.deepEqual(errors, []);
  await writeFile('research/browser-controls/results.json', JSON.stringify({ checks, pageErrors: errors, status: 'passed' }, null, 2) + '\n');
  console.log(JSON.stringify({ checks, pageErrors: errors, status: 'passed' }, null, 2));
} finally { await browser.close(); }
